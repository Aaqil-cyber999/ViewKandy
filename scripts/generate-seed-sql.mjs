/**
 * Generates supabase/seed.sql from data/seed/*.json so the database and the
 * bundled fallback dataset can never drift apart.
 *
 * Run with: npm run seed:sql
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const categories = JSON.parse(
  readFileSync(resolve(root, "data", "seed", "categories.json"), "utf8"),
);
const places = JSON.parse(
  readFileSync(resolve(root, "data", "seed", "places.json"), "utf8"),
);

const text = (value) =>
  value === null || value === undefined ? "null" : `'${String(value).replace(/'/g, "''")}'`;

const number = (value) =>
  value === null || value === undefined ? "null" : String(value);

const boolean = (value) => (value ? "true" : "false");

const textArray = (values) =>
  !values || values.length === 0
    ? "'{}'::text[]"
    : `array[${values.map(text).join(", ")}]::text[]`;

const lines = [];
lines.push("-- Generated by scripts/generate-seed-sql.mjs — do not edit by hand.");
lines.push("-- Applies the bundled KandyVerse seed dataset to the Supabase schema.");
lines.push("-- Every seeded place is intentionally 'unverified' with null hours/fees/phones.");
lines.push("");
lines.push("begin;");
lines.push("");

lines.push(
  'insert into public.categories (id, slug, name, description, color, icon, "order") values',
);
lines.push(
  categories
    .map(
      (category) =>
        `  (${text(category.id)}, ${text(category.slug)}, ${text(category.name)}, ${text(
          category.description,
        )}, ${text(category.color)}, ${text(category.icon)}, ${number(category.order)})`,
    )
    .join(",\n"),
);
lines.push("on conflict (id) do update set");
lines.push("  slug = excluded.slug,");
lines.push("  name = excluded.name,");
lines.push("  description = excluded.description,");
lines.push("  color = excluded.color,");
lines.push("  icon = excluded.icon,");
lines.push('  "order" = excluded."order";');
lines.push("");

const columns = [
  "id",
  "slug",
  "name",
  "category_slug",
  "summary",
  "description",
  "lat",
  "lng",
  "address",
  "website",
  "phone",
  "opening_hours",
  "entry_fee_lkr",
  "estimated_visit_minutes",
  "accessibility",
  "tags",
  "indoor",
  "best_time",
  "practical_notes",
  "verification_status",
  "verification_source",
  "verification_source_url",
  "last_verified_at",
  "location_accuracy",
  "featured",
  "priority",
];

const rows = places.map((place) =>
  [
    text(place.id),
    text(place.slug),
    text(place.name),
    text(place.category),
    text(place.summary),
    text(place.description),
    number(place.lat),
    number(place.lng),
    text(place.address),
    text(place.website),
    text(place.phone),
    text(place.openingHours),
    number(place.entryFeeLkr),
    number(place.estimatedVisitMinutes),
    text(place.accessibility),
    textArray(place.tags),
    boolean(place.indoor),
    text(place.bestTime),
    text(place.practicalNotes),
    text(place.verification.status),
    text(place.verification.source),
    text(place.verification.sourceUrl),
    text(place.verification.lastVerifiedAt),
    text(place.locationAccuracy),
    boolean(place.featured),
    number(place.priority),
  ].join(", "),
);

lines.push(`insert into public.places (${columns.join(", ")}) values`);
lines.push(rows.map((row) => `  (${row})`).join(",\n"));
lines.push("on conflict (id) do update set");
const updatable = columns.filter((column) => column !== "id");
lines.push(
  updatable.map((column) => `  ${column} = excluded.${column}`).join(",\n") + ";",
);
lines.push("");
lines.push("commit;");
lines.push("");

const output = resolve(root, "supabase", "seed.sql");
writeFileSync(output, lines.join("\n"), "utf8");
console.log(
  `[seed:sql] wrote supabase/seed.sql (${categories.length} categories, ${places.length} places)`,
);
